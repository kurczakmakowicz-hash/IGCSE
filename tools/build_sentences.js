/* Bundle the example sentences (content/french/sentences/*.json) into
 * data/french_sentences.js: {"<list entry>": ["French sentence.", "English."]}.
 * Refuses to write anything unless every list entry has a valid sentence.
 *   node tools/build_sentences.js
 */
const fs = require('fs');
const path = require('path');
const { validate, DIR } = require('./validate_sentences.js');

const files = fs.readdirSync(DIR).filter((f) => f.endsWith('.json')).sort().map((f) => path.join(DIR, f));
const errs = validate(files, true);
if (errs.length) {
  console.error(errs.slice(0, 50).join('\n') + '\n\n' + errs.length + ' problem(s); nothing written.');
  process.exit(1);
}
const out = {};
files.forEach((f) => JSON.parse(fs.readFileSync(f, 'utf8')).forEach((e) => { out[e.w] = [e.fr, e.en]; }));
const dest = path.join(__dirname, '..', 'data', 'french_sentences.js');
fs.writeFileSync(dest,
  '// Generated by tools/build_sentences.js from content/french/sentences/*.json.\n' +
  '// Edit the JSON files, not this one.\n' +
  'window.IGCSE_DATA = window.IGCSE_DATA || {};\n' +
  'window.IGCSE_DATA.frenchSentences = ' + JSON.stringify(out) + ';\n');
console.log('sentences  ' + Object.keys(out).length + ' entries -> data/french_sentences.js');
