/* Bundle the French grammar topics (content/french/grammar/*.json) into
 * data/french_grammar.js, which the app loads with a plain <script> tag so it
 * still works from file://. Refuses to write anything if a topic is invalid.
 *   node tools/build_grammar.js
 */
const fs = require('fs');
const path = require('path');
const { validateFiles, filesFrom } = require('./validate_grammar.js');

const root = path.join(__dirname, '..');
const files = filesFrom([]);
const errs = validateFiles(files);
if (errs.length) {
  console.error(errs.join('\n') + '\n\n' + errs.length + ' problem(s); nothing written.');
  process.exit(1);
}
const topics = files.map((f) => JSON.parse(fs.readFileSync(f, 'utf8')))
  .sort((a, b) => a.order - b.order);
const out = path.join(root, 'data', 'french_grammar.js');
fs.writeFileSync(out,
  '// Generated by tools/build_grammar.js from content/french/grammar/*.json.\n' +
  '// Edit the JSON files, not this one.\n' +
  'window.IGCSE_DATA = window.IGCSE_DATA || {};\n' +
  'window.IGCSE_DATA.frenchGrammar = ' + JSON.stringify({ topics }) + ';\n');
const cards = topics.reduce((n, t) => n + t.cards.length, 0);
console.log('grammar    ' + topics.length + ' topics ' + String(cards).padStart(5) + ' cards  -> data/french_grammar.js');
